with open(PATH, encoding='utf-8') as f:
    items = json.load(f)

updated = []
for item in items:
    slug = item.get('slug')
    if slug not in CONTENT:
        continue
    content = item.get('sections', {}).get('content', [])
    fill = CONTENT[slug]
    # Обновляем существующие секции по заголовку (без учёта иконок)
    for sec in content:
        heading = sec.get('heading', '')
        # Убираем префикс иконки для сравнения
        clean = re.sub(r'^!\[icon\]\([^)]*\)\s*', '', heading).strip().upper()
        if clean in fill:
            sec['body'] = fill[clean]
            del fill[clean]
    # Добавляем недостающие секции (например, СУТЬ у адренохрома)
    for heading, body in fill.items():
        content.append({'heading': heading, 'body': body})
    updated.append(slug)

with open(PATH, 'w', encoding='utf-8') as f:
    json.dump(items, f, ensure_ascii=False, indent=2)

print('Обновлено статей:', len(updated))
for slug in updated:
    print(' -', slug)